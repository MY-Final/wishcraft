import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const families = [
  {
    css: 'https://fonts.googleapis.com/css2?family=Inter+Tight:wght@400..600&display=swap',
    key: 'inter-tight',
  },
  {
    css: 'https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&display=swap',
    key: 'ibm-plex-mono',
  },
];

const outDir = resolve('public/fonts');
mkdirSync(outDir, { recursive: true });

let cssOut = '/* Self-hosted latin subsets. Generated by tools/fetch-fonts.mjs */\n';

for (const family of families) {
  const css = await (await fetch(family.css, { headers: { 'User-Agent': UA } })).text();
  const blocks = css.split('/*').filter((block) => block.includes('latin */'));
  for (const block of blocks) {
    const weight = /font-weight:\s*([^;]+);/.exec(block)?.[1]?.trim() ?? '400';
    const url = /url\((https:[^)]+)\)/.exec(block)?.[1];
    if (!url) continue;
    const name = `${family.key}-${weight.replace(/\s+/g, '-')}.woff2`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`font download failed ${url}`);
    const buffer = Buffer.from(await response.arrayBuffer());
    writeFileSync(resolve(outDir, name), buffer);
    cssOut += `@font-face {\n  font-family: '${family.key === 'inter-tight' ? 'Inter Tight' : 'IBM Plex Mono'}';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('/fonts/${name}') format('woff2');\n  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;\n}\n`;
    console.log(`${name} ${Math.round(buffer.length / 1024)}KB`);
  }
}

writeFileSync(resolve('src/styles/fonts.css'), cssOut);
console.log('written src/styles/fonts.css');
